import { test, expect } from '@playwright/test';

test('cadastro, receita, busca, edição, impressão, persistência, exclusão e logout', async ({ page }) => {
  const login = `e2e_${Date.now()}_${Math.random().toString(36).slice(2, 7)}`;
  await page.goto('/');
  await page.getByRole('tab', { name: 'Cadastrar', exact: true }).click();
  await expect(page.getByRole('tab', { name: 'Cadastrar' })).toHaveAttribute('aria-selected', 'true');
  await page.getByLabel('Seu nome').fill('Pessoa Cozinheira');
  await page.getByLabel('Login ou e-mail').fill(login);
  await page.getByLabel('Senha', { exact: true }).fill('teste@123');
  await page.getByRole('button', { name: 'Criar meu caderno', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Meu caderno de receitas.' })).toBeVisible();
  await expect(page.getByText('Seu caderno está esperando a primeira receita.')).toBeVisible();
  await page.getByRole('button', { name: 'Nova receita', exact: true }).click();
  const form = page.getByRole('dialog');
  await form.getByLabel('Nome da receita').fill('Sopa da horta');
  await form.getByLabel('Categoria', { exact: true }).selectOption({ label: 'Sopas' });
  await form.getByLabel('Tempo de preparo (min)').fill('25');
  await form.getByLabel('Porções', { exact: true }).fill('3');
  await form.getByLabel('Ingredientes').fill('2 batatas\n1 cenoura\n1 litro de caldo');
  await form.getByLabel('Modo de preparo').fill('Pique os legumes.\nCozinhe no caldo por 25 minutos.');
  await form.getByRole('button', { name: 'Salvar receita' }).click();
  const detail = page.getByRole('dialog');
  await expect(detail.getByRole('heading', { name: 'Sopa da horta' })).toBeVisible();
  await detail.getByRole('checkbox').first().check();
  await expect(detail.getByRole('checkbox').first()).toBeChecked();
  await detail.getByRole('button', { name: 'Editar receita' }).click();
  await page.getByLabel('Nome da receita').fill('Sopa da horta especial');
  await page.getByRole('button', { name: 'Salvar receita' }).click();
  await expect(detail.getByRole('heading', { name: 'Sopa da horta especial' })).toBeVisible();
  await page.evaluate(() => { (window as any).__printed = false; window.print = () => { (window as any).__printed = true; }; });
  await detail.getByRole('button', { name: 'Imprimir', exact: true }).click();
  expect(await page.evaluate(() => (window as any).__printed)).toBe(true);
  await page.emulateMedia({ media: 'print' });
  await expect(page.locator('.detail-actions')).toBeHidden();
  await expect(detail.getByRole('heading', { name: 'Ingredientes' })).toBeVisible();
  await page.emulateMedia({ media: 'screen' });
  await detail.getByRole('button', { name: 'Fechar receita' }).click();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Sopa da horta especial' })).toBeVisible();
  await page.getByRole('textbox', { name: 'Buscar receitas' }).fill('cenoura');
  await expect(page.getByRole('heading', { name: 'Sopa da horta especial' })).toBeVisible();
  await page.getByRole('textbox', { name: 'Buscar receitas' }).fill('chocolate');
  await expect(page.getByText('Nenhuma receita por aqui.')).toBeVisible();
  await page.getByRole('button', { name: 'Limpar busca', exact: true }).click();
  await page.getByRole('combobox', { name: 'Filtrar por categoria' }).selectOption({ label: 'Massas' });
  await expect(page.getByText('Nenhuma receita por aqui.')).toBeVisible();
  await page.getByRole('combobox', { name: 'Filtrar por categoria' }).selectOption('');
  await page.getByRole('button', { name: 'Visualizar em lista' }).click();
  await page.getByRole('button').filter({ has: page.getByRole('heading', { name: 'Sopa da horta especial' }) }).click();
  await detail.getByRole('button', { name: 'Excluir receita', exact: true }).click();
  await detail.getByRole('button', { name: 'Manter receita' }).click();
  await detail.getByRole('button', { name: 'Excluir receita', exact: true }).click();
  await detail.getByRole('button', { name: 'Sim, excluir' }).click();
  await expect(page.getByText('Seu caderno está esperando a primeira receita.')).toBeVisible();
  if (await page.getByRole('button', { name: 'Abrir menu' }).isVisible()) await page.getByRole('button', { name: 'Abrir menu' }).click();
  await page.getByRole('button', { name: 'Sair da conta' }).click();
  await expect(page.getByRole('button', { name: 'Abrir meu caderno' })).toBeVisible();
  await page.getByLabel('Login ou e-mail').fill(login);
  await page.getByLabel('Senha', { exact: true }).fill('teste@123');
  await page.getByRole('button', { name: 'Abrir meu caderno' }).click();
  await expect(page.getByText('Seu caderno está esperando a primeira receita.')).toBeVisible();
});

test('login incorreto apresenta erro e layout cabe na tela', async ({ page }) => {
  await page.goto('/');
  const loginTab = page.getByRole('tab', { name: 'Entrar', exact: true });
  await expect(loginTab).toHaveAttribute('aria-selected', 'true');
  await loginTab.focus();
  await page.keyboard.press('ArrowRight');
  await expect(page.getByLabel('Seu nome')).toBeVisible();
  await page.keyboard.press('ArrowLeft');
  await expect(page.getByLabel('Seu nome')).toHaveCount(0);
  await expect(loginTab).toBeFocused();
  await page.getByLabel('Login ou e-mail').fill('conta_inexistente');
  await page.getByLabel('Senha', { exact: true }).fill('SenhaIncorreta');
  await page.getByRole('button', { name: 'Abrir meu caderno' }).click();
  await expect(page.getByRole('alert')).toHaveText('Login ou senha incorretos.');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});
